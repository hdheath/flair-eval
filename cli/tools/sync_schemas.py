#!/usr/bin/env python3
"""Copy the contract schemas (assets/schema/*.json) to where the front ends read them.

    cli/src/flair_eval/schemas/*.json   bundled with the pip package (verbatim copies)
    frontend/builder/schemas.js         samples + runs schemas for the builder page

Run it after assets/schema changes:   python cli/tools/sync_schemas.py
In CI:                                python cli/tools/sync_schemas.py --check
"""

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / "assets" / "schema"
CLI_DIR = REPO / "cli" / "src" / "flair_eval" / "schemas"
JS_FILE = REPO / "frontend" / "builder" / "schemas.js"
JS_SCHEMAS = ("samples", "runs")


def render_js() -> str:
    data = {n: json.loads((SRC / f"{n}.schema.json").read_text()) for n in JS_SCHEMAS}
    body = json.dumps(data, indent=2, ensure_ascii=False)
    return ("/* Generated by cli/tools/sync_schemas.py from assets/schema/*.json. Do not edit. */\n"
            "(function (g) {\n"
            f"  var S = {body};\n"
            '  if (typeof module !== "undefined" && module.exports) module.exports = S;\n'
            "  else g.FLAIR_EVAL_SCHEMAS = S;\n"
            '})(typeof self !== "undefined" ? self : this);\n')


def targets() -> dict:
    out = {CLI_DIR / p.name: p.read_text() for p in sorted(SRC.glob("*.schema.json"))}
    out[JS_FILE] = render_js()
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if any copy is out of date")
    a = ap.parse_args(argv)
    stale = [p for p, text in targets().items() if not p.exists() or p.read_text() != text]
    if a.check:
        for p in stale:
            print(f"out of date: {p.relative_to(REPO)}", file=sys.stderr)
        if stale:
            print("run: python cli/tools/sync_schemas.py", file=sys.stderr)
        return 1 if stale else 0
    for p, text in targets().items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    print(f"updated {len(stale)} file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
